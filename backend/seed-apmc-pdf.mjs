async function runSeed() {
  console.log(`Starting to seed ${apmcPdfData.length} APMC Mandi price records...`);

  // Clear existing market_prices
  const { error: delError } = await supabase.from('market_prices').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  if (delError) console.warn('Note on delete:', delError.message);

  // Insert in batches of 20
  const batchSize = 20;
  for (let i = 0; i < apmcPdfData.length; i += batchSize) {
    const chunk = apmcPdfData.slice(i, i + batchSize);
    const { error } = await supabase.from('market_prices').insert(chunk);
    if (error) {
      console.error(`Error inserting batch ${i}:`, error.message);
    } else {
      console.log(`Inserted batch ${i + 1} to ${Math.min(i + batchSize, apmcPdfData.length)}`);
    }
  }

  const { count, error: countErr } = await supabase.from('market_prices').select('*', { count: 'exact', head: true });
  console.log(`\nDONE! Total active rows in public.market_prices: ${count}`);
}

runSeed().catch(console.error);
